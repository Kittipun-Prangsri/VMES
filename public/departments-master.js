/* ============================================================================
 * รายชื่อหน่วยงานจริงของโรงพยาบาล (ยืนยันโดยผู้ดูแลระบบ) — ใช้เป็นตัวเลือกหน่วยงานทุกหน้า (เว็บ/LIFF/ใบส่งมอบ)
 *
 * แหล่งจริงอยู่ที่ backend-node/lib/departmentsMaster.js; `npm run build` คัดลอกไป public/departments-master.js
 * (มีเทสต์เช็กว่าสำเร็จเหมือนกันเสมอ) — ไฟล์นี้จึงห้ามอ้างอะไรที่มีเฉพาะ Node
 *
 * ตัวเลือกที่แสดง = REAL + หน่วยงานที่ผู้ดูแลเพิ่มเองในตารางหน่วยงาน − LEGACY (ชื่อทดสอบ/ชื่อเก่าที่ไม่ใช่หน่วยงานจริง)
 * ข้อมูลเก่าที่ใช้ชื่อใน LEGACY ยังอยู่ครบ แค่ไม่ถูกเสนอเป็นตัวเลือกใหม่
 * ========================================================================== */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.DeptMaster = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  const REAL = [
    'งานการเงิน', 'งานพัสดุ', 'งานธุรการ', 'งานซ่อมบำรุง', 'งานยานพาหนะ', 'งานรังสีวินิจฉัย',
    'ชันสุตร (จุลทรรศนศาสตร์คลีนิก และโลหิตวิทยา)', 'งานกายภาพบำบัด', 'งานทันตกรรม', 'งานประกันสุขภาพ',
    'งานเวชระเบียนและห้องบัตร', 'งานเภสัชกรรม', 'งานแพทย์แผนไทย', 'งานการแพทย์', 'งานการพยาบาลผู้ป่วยนอก',
    'งานการพยาบาลผู้ป่วยอุบัติเหตุฉุกเฉินและนิติเวช', 'งานการพยาบาลผู้คลอด', 'งานทำความสะอาด', 'งานรักษาความปลอดภัย',
    'งานซักฟอก', 'กลุ่มงานการพยาบาล', 'งานพยาบาลหน่วยควบคุมการติดเชื้อและงานจ่ายกลาง', 'IC', 'งานบริหารทั่วไป',
    'การพยาบาล', 'งานการพยาบาลผู้ป่วยใน', 'งานยุทธศาสตร์', 'งานบริการปฐมภูมิ', 'งานสารสนเทศ', 'งานจิตเวช', 'งานโภชนศาสตร์',
  ];
  const LEGACY = [
    'งานการพยาบาล', 'งานเทคโนโลยีสารสนเทศ', 'งานเภสัชกรรม (ห้องยา)', 'งานเวชและประฐมภูมิ', 'งานสุขภาพจิตและยาเสพติด',
    'ทันตกรรม', 'ผู้ป่วยนอก', 'ผู้ป่วยนอก (OPD)', 'ผู้ป่วยใน (IPD)', 'ฝ่ายบริหาร / สำนักงาน', 'ห้องคลอด', 'อิทธิพล คนจริง',
    'อุบัติเหตุและฉุกเฉิน (ER)',
  ];

  const norm = (v) => String(v == null ? '' : v).replace(/\s+/g, ' ').trim();
  const key = (v) => norm(v).replace(/\s+/g, '').toLowerCase();
  const legacyKeys = new Set(LEGACY.map(key));

  // dbNames: ชื่อจากตารางหน่วยงาน (อาจว่าง/ไม่ส่งมา) -> รายการที่แสดง เรียงตามตัวอักษรไทย ไม่ซ้ำ
  function merge(dbNames) {
    const seen = new Set();
    const out = [];
    REAL.concat((dbNames || []).filter((n) => !legacyKeys.has(key(n)))).forEach((n) => {
      const nn = norm(n), k = key(n);
      if (nn && !seen.has(k)) { seen.add(k); out.push(nn); }
    });
    return out.sort((a, b) => a.localeCompare(b, 'th'));
  }
  const find = (name, dbNames) => merge(dbNames).find((n) => key(n) === key(name));

  return { REAL, LEGACY, norm, key, merge, find };
});
